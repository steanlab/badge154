#!/usr/bin/env python3
"""Renders the start-up screen (200 x 200, 1 bit per pixel) into firmware/src/splash.h.

Usage: python3 tools/make_splash.py [font.ttf] [preview.png]
Needs Pillow. The default font is DejaVu Sans Bold (free licence, https://dejavu-fonts.github.io/).
Change LINES to change the text; each line is shrunk until it fits the width.
"""
import sys, pathlib
from PIL import Image, ImageDraw, ImageFont

LINES = [("BADGE154", 40), ("PROJECT", 28), ("Siarhei Besarab (steanlab)", 16)]   # text, preferred size in px
INVERT = True                 # True: white text on black, False: black text on white
GAP = 18                      # extra space between the lines
W = H = 200
MARGIN = 8
font_path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
preview = sys.argv[2] if len(sys.argv) > 2 else None

def fit(text, size):
    while size > 6:
        f = ImageFont.truetype(font_path, size)
        l, t, r, b = f.getbbox(text)
        if r - l <= W - 2 * MARGIN:
            return f, (l, t, r, b)
        size -= 1
    raise SystemExit("text does not fit: " + text)

items = [(text,) + fit(text, size) for text, size in LINES]
total = sum(b - t for _, f, (l, t, r, b) in items) + GAP * (len(items) - 1)
y = (H - total) // 2
BG, FG = (0, 1) if INVERT else (1, 0)
img = Image.new("1", (W, H), BG)
d = ImageDraw.Draw(img)
d.fontmode = "1"                               # no anti-aliasing: crisp pixels
for text, f, (l, t, r, b) in items:
    x = (W - (r - l)) // 2 - l
    d.text((x, y - t), text, font=f, fill=FG)
    y += (b - t) + GAP

data = bytearray()
for yy in range(H):
    for xx in range(0, W, 8):
        v = 0
        for k in range(8):
            v = (v << 1) | (1 if img.getpixel((xx + k, yy)) == 0 else 0)   # bit set = black pixel
        data.append(v)

out = pathlib.Path(__file__).resolve().parent.parent / "firmware" / "src" / "splash.h"
lines = ["#pragma once", "#include <stdint.h>", "",
         "/* Generated by tools/make_splash.py, do not edit. 200 x 200, 1 bit per pixel, first pixel in the top bit,",
         "   bit set = black, rows from top to bottom (25 bytes per row). */",
         "static const uint8_t splash_1bpp[5000] = {"]
for i in range(0, len(data), 16):
    lines.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
lines.append("};")
out.write_text("\n".join(lines) + "\n")
print("wrote", out, len(data), "bytes")
if preview:
    img.resize((400, 400), Image.NEAREST).save(preview)
